const byType = new Map<ModuleType, ModuleDefinition>(moduleDefinitions.map((m) => [m.type, m]));
const dataTypeById = new Map(dataTypes.map((d) => [d.id, d]));

export function getModuleDefinition(type: string): ModuleDefinition | undefined {
  return byType.get(type as ModuleType);
}

export function getDataType(id: string): DataTypeDefinition | undefined {
  return dataTypeById.get(id);
}

/** Output data type may feed an input if identical or explicitly assignable. */
export function isCompatible(sourceType: string, targetType: string): boolean {
  if (sourceType === targetType) return true;
  return getDataType(sourceType)?.assignableTo.includes(targetType) ?? false;
}
